def apply_steps(cfg: dict) -> dict:
    """Assignment of /tf-task loop steps (`steps`): a step's tier becomes the tier of its executor (the shared agent)."""
    agents = cfg.get("shared_agents") or {}
    for step in (cfg.get("steps") or {}).values():
        if isinstance(step, dict) and step.get("who") in agents and step.get("tier") in (cfg.get("tiers") or {}):
            agents[step["who"]]["tier"] = step["tier"]
    return cfg


def steps_errors(cfg: dict) -> list[str]:
    """`steps` configuration errors: a missing field, an unknown executor or tier, an executor with two different tiers."""
    errors, seen = [], {}
    for sid, step in (cfg.get("steps") or {}).items():
        if not isinstance(step, dict) or not all(step.get(k) for k in ("label", "who", "tier")):
            errors.append(f"steps.{sid}: a step must have the fields label, who and tier")
            continue
        if step["who"] not in (cfg.get("shared_agents") or {}):
            errors.append(f"steps.{sid}: unknown executor '{step['who']}' (a shared agent from shared_agents)")
        if step["tier"] not in (cfg.get("tiers") or {}):
            errors.append(f"steps.{sid}: unknown tier '{step['tier']}'")
        if seen.setdefault(step["who"], step["tier"]) != step["tier"]:
            errors.append(f"steps.{sid}: executor '{step['who']}' has two different tiers in the steps "
                          f"({seen[step['who']]} and {step['tier']}) — an agent has one model")
    return errors


def steps_table_errors(cfg: dict, skill_text: str) -> list[str]:
    """The “Who does what” table in the loop skill against `steps`: every step has a row with the same executor and tier."""
    head = "## Who does what" if "## Who does what" in skill_text else None
    section = skill_text.split(head, 1)[-1].split("\n## ", 1)[0] if head else ""
    rows = {}
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.strip().startswith("|") and len(cells) == 3 and cells[0] not in ("Krok", "Step", "") and not set(cells[0]) <= {"-"}:
            rows[cells[0]] = (cells[1], cells[2])
    errors = []
    steps = {s["label"]: s for s in (cfg.get("steps") or {}).values() if isinstance(s, dict) and s.get("label")}
    for label, step in steps.items():
        if label not in rows:
            errors.append(f"skill tf, table \"Who does what\": no row for the step \"{label}\" (steps in the configuration)")
        elif f"`{step.get('who')}`" not in rows[label][0] or rows[label][1] != step.get("tier"):
            errors.append(f"skill tf, table \"Who does what\": the step \"{label}\" has in the configuration the executor "
                          f"`{step.get('who')}` and tier {step.get('tier')}, and in the table: {rows[label][0]} / {rows[label][1]}")
    errors += [f"skill tf, table \"Who does what\": the row \"{label}\" has no step in the configuration (steps)"
               for label in rows if label not in steps]
    return errors


