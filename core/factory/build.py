def cmd_build():
    rendered = render_all()
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    for rel, txt in rendered.items():
        p = OUT_DIR / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(txt, encoding="utf-8")
    CATALOG.write_text(render_catalog(), encoding="utf-8")
    tocs = 0
    for ref in reference_files():
        old = ref.read_text(encoding="utf-8")
        new = with_toc(old)
        if new != old:
            ref.write_text(new, encoding="utf-8")
            tocs += 1
    if tocs:
        print(f"✓ Tables of contents updated in {tocs} reference files")
    print(f"✓ Generated {len(rendered)} agents in {OUT_DIR.relative_to(ROOT)} and the catalog {CATALOG.relative_to(ROOT)}"
          f" (cost profile: {load_config()['_profile']})")
    tm = managed_target()
    if tm:
        files, _w, _e = tm.render(sys.modules[__name__])
        tm.write(TARGETS["managed-agents"], files)
        print(f"✓ Managed Agents: {sum(k.startswith('agents/') for k in files)} agents in "
              f"{TARGETS['managed-agents'].relative_to(ROOT)}/ — nothing was sent; plan and upload: "
              "python3 .tf/factory/build.py managed-apply [--yes]")
    errors, warnings = validate()
    try:   # add-ons (.tf/addons/): wire their output in; a broken add-on never fails the build
        import addons as addons_mod  # noqa: E402
        warnings += addons_mod.sync(ROOT, quiet=True)
    except Exception as e:  # noqa: BLE001
        warnings.append(f"add-ons not synced: {e}")
    for w in warnings:
        print(f"  ⚠ {w}")
    for e in errors:
        print(f"  ✗ {e}")
    return 1 if errors else 0


