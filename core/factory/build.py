def skill_listing(entries: dict[str, int], stack_slots: int, marked: set[str] = frozenset(),
                  name_only: tuple[str, ...] = ()) -> int:
    """The size of the skill list in a typical project: entries with a description per skill_profile (empty stack) + `stack_slots`
    longest technology entries (fw-/lang-/tool-) the project may detect. `entries`: name → entry characters;
    `marked`: skills with `metadata.visibility: name`."""
    sp = _skill_profile()
    base = sum(n for name, n in entries.items() if sp.desired(name, set(), name in marked, (), name_only) == "on")
    stack = sorted((n for name, n in entries.items() if name.startswith(sp.STACK_PREFIXES)), reverse=True)
    return base + sum(stack[:stack_slots])


def skill_usage(skills, used: set, cfg: dict) -> tuple[list[str], list[str]]:
    """Skills without a role and persona. Those listed in `standalone_skills` (called manually, e.g. domain knowledge) do not
    get a warning; an unknown entry is an error, and an entry of a skill a persona already uses is redundant."""
    standalone = cfg.get("standalone_skills") or []
    inactive = set(cfg.get("_inactive") or [])
    errors = [f"standalone_skills: unknown skill '{s}'" for s in standalone if s not in skills]
    warnings = [f"skill {s}: not used by any role or persona" for s in skills
                if s not in used and s not in standalone and s not in inactive
                and not s.startswith("core-")]   # core-* is a library for overlays
    warnings += [f"skill {s}: used by a role or persona — a redundant entry in standalone_skills" for s in standalone
                 if s in skills and s in used]
    return errors, warnings


def version_ok(version: str, spec: str) -> bool:
    """A simple SemVer range: conditions `>=X.Y.Z`, `>X.Y.Z`, `<X.Y.Z`, `<=X.Y.Z`, `==X.Y.Z` separated by a space."""
    def t(v: str) -> tuple[int, ...]:
        return tuple(int(x) for x in re.findall(r"\d+", v)[:3])
    ops = {">=": lambda a, b: a >= b, "<=": lambda a, b: a <= b, ">": lambda a, b: a > b,
           "<": lambda a, b: a < b, "==": lambda a, b: a == b}
    for cond in str(spec).split():
        op = next((o for o in (">=", "<=", "==", ">", "<") if cond.startswith(o)), "==")
        if not ops[op](t(version), t(cond[len(op):] if cond.startswith(op) else cond)):
            return False
    return True


def check_packs(cfg: dict) -> tuple[list[str], list[str]]:
    """Compatibility of overlays with the core and with each other: core version, required overlays, language overlay."""
    errors, warnings = [], []
    packs = cfg.get("_packs") or {}
    core_version = (FACTORY / "VERSION").read_text(encoding="utf-8").strip() if (FACTORY / "VERSION").exists() else "0.0.0"
    for pid, p in packs.items():
        if p.get("_dir") and p["_dir"].name != pid:
            errors.append(f"pack {pid}: directory .tf/factory/packs/{p['_dir'].name} ≠ id")
        spec = (p.get("requires") or {}).get("core")
        if spec and not version_ok(core_version, spec):
            errors.append(f"pack {pid}: requires core {spec}, and {core_version} is installed — "
                          f"update the factory (tf update) or the pack")
        for dep in (p.get("requires") or {}).get("packs") or []:
            if dep not in packs:
                errors.append(f"pack {pid}: requires the pack {dep} — tf add {dep}")
    return errors, warnings


def validate() -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    cfg = load_config()
    lim = cfg["limits"]
    roles, personas, traits, skills, team_errors = load_team(cfg)
    personas_raw = load_dir("personas")
    errors += cfg.get("_errors") or []
    errors += team_errors
    errors += [f"target '{t}' is not supported (available: {', '.join(TARGETS)})"
               for t in cfg["_settings"]["targets"] if t not in TARGETS]
    tm = managed_target()
    if tm:
        files, w, e = tm.render(sys.modules[__name__])
        errors += e
        warnings += w
        if tm.stale(TARGETS["managed-agents"], files):
            errors.append("files in managed-agents/ are stale — run: python3 .tf/factory/build.py")
    for sub in ("roles", "personas"):
        warnings += packs_mod.load_items(ROOT, sub)[1]
    e, w = check_packs(cfg)
    errors += e
    warnings += w

    vocab = [v.lower() for v in cfg.get("vocabulary", [])]
    contract_prefixes = tuple(f["prefix"] for f in cfg["facets"] if f.get("contract"))
    for name, s in skills.items():
        if name.startswith(contract_prefixes):
            body = (SKILLS_DIR / s["_dir"] / "SKILL.md").read_text(encoding="utf-8")
            refs = " ".join(x.read_text(encoding="utf-8") for x in (SKILLS_DIR / s["_dir"]).glob("references/*.md"))
            if "## Domain concepts" not in body:
                errors.append(f"skill {name}: no \"## Domain concepts in …\" section (the technology skills' contract)")
            else:
                text = (body + refs).lower()
                missing = [v for v in vocab if v not in text]
                if missing:
                    warnings.append(f"skill {name}: the vocabulary does not cover the concepts: {', '.join(missing)}")
    versioned_prefixes = tuple(f["prefix"] for f in cfg["facets"] if f.get("versioned"))
    for name, s in skills.items():
        if name.startswith(versioned_prefixes) and name not in cfg.get("unversioned_skills", []):
            meta_path = SKILLS_DIR / s["_dir"] / "skill.meta.json"
            if not meta_path.exists():
                errors.append(f"skill {name}: no skill.meta.json (based_on, min_supported, sources) — needed for version sync")
                continue
            try:
                meta = json.loads(meta_path.read_text(encoding="utf-8"))
            except json.JSONDecodeError as e:
                errors.append(f"skill {name}: skill.meta.json is invalid JSON ({e})"); continue
            for key in ("based_on", "min_supported", "sources", "verified"):
                if not meta.get(key):
                    errors.append(f"skill {name}: skill.meta.json without the field '{key}'")
            text = (SKILLS_DIR / s["_dir"] / "SKILL.md").read_text(encoding="utf-8")
            if "## Version-dependent" not in text:
                errors.append(f"skill {name}: no \"## Version-dependent\" section (what works from which version)")
    registries = [SKILLS_DIR / "core-stack-sync" / "references" / "technologies.json",
                  *sorted((FACTORY / "packs").glob("*/technologies.json"))]
    for registry in (r for r in registries if r.exists()):
        for t in json.loads(registry.read_text(encoding="utf-8")).get("technologies", []):
            if not t["skill"].startswith(skill_prefixes(cfg)):
                errors.append(f"technologies.json: skill '{t['skill']}' without a dimension prefix")
    for req_owner, reqs in (cfg.get("skill_requires") or {}).items():
        for r in [req_owner, *reqs]:
            if r not in skills:
                errors.append(f"skill_requires: unknown skill '{r}'")
    for pname, prof in (cfg.get("profiles") or {}).items():
        for tier, over in ((prof or {}).get("tiers") or {}).items():
            if tier not in cfg["tiers"]:
                errors.append(f"profiles.{pname}: unknown tier '{tier}'")
            elif (over or {}).get("model") and over["model"] not in ("haiku", "sonnet", "opus", "fable", "inherit") \
                    and not str(over["model"]).startswith("claude-"):
                errors.append(f"profiles.{pname}.{tier}: unknown model '{over['model']}'")
    if cfg.get("profiles") and cfg.get("default_profile") not in cfg["profiles"]:
        errors.append(f"default_profile '{cfg.get('default_profile')}' is not in profiles")
    for a in cfg.get("always_skills") or []:
        if a not in skills:
            errors.append(f"always_skills: unknown skill '{a}'")
    listing: dict[str, int] = {}
    gate = gate_registry()
    for name, s in skills.items():
        if name != s["_dir"]:
            errors.append(f"skill {s['_dir']}: name '{name}' ≠ the folder name")
        if not name.startswith(skill_prefixes(cfg)):   # a project skill from outside the factory — we do not judge it by factory rules
            warnings.append(f"skill {name}: outside the factory (no dimension prefix) — skipped in validation; "
                            "for a persona to use it, give it a prefix from .tf/config/config.yaml → facets")
            continue
        d = s.get("description", "")
        katalog = (s.get("metadata") or {}).get("catalog", "")
        if not d:
            errors.append(f"skill {name}: no description")
        elif len(d) > lim["skill_description_max_chars"]:
            errors.append(f"skill {name}: description has {len(d)} characters (> {lim['skill_description_max_chars']}) — "
                          "briefly what and when; the boundaries (\"Not for …\") in metadata.catalog")
        if d and not re.search(r"\b(Użyj|użyj|gdy|kiedy|przy\s|Use|use|when|whenever)\b", d):
            warnings.append(f"skill {name}: description is not a selection rule — start with \"Use when/for …\"; Claude Code "
                            "shows the model only the description (it skips the metadata field)")
        e, w = check_review_date(name, s.get("metadata") or {})
        errors += e
        warnings += w
        if not katalog:
            warnings.append(f"skill {name}: no metadata.catalog (the full description with boundaries for the dispatcher's catalog)")
        elif not re.search(r"\b(nie|not)\b", katalog.lower()):
            warnings.append(f"skill {name}: metadata.catalog does not set boundaries (what the skill does NOT cover)")
        if not s.get("disable-model-invocation"):
            listing[name] = len(name) + len(d) + 4
        for field in ("model", "effort"):
            if s.get(field):
                warnings.append(f"skill {name}: the field {field} changes the model or effort mid-turn — the next request reads "
                                "the whole history without cache (code.claude.com, \"Prompt caching\"); remove it")
        if s.get("paths"):
            warnings.append(f"skill {name}: the field paths hides the skill from the model until the session has a matching file "
                            "(\"Unknown skill\" even on an explicit call) — remove it; the skill_hint hook triggers it")
        if not any((ROOT / d / "skill_evals" / f"{name}.json").exists() for d in ("tests", ".claude/tests")):
            warnings.append(f"skill {name}: no evaluation scenarios (tests/skill_evals/{name}.json, at least 3) — "
                            "the format is in tests/skill_evals/README.md")
        if s.get("_chars", 0) > lim.get("skill_body_max_chars", 10**9):
            warnings.append(f"skill {name}: SKILL.md has {s['_chars']} characters (> {lim['skill_body_max_chars']}) — after "
                            "compaction Claude Code restores at most ~5000 tokens of a skill; move details to references/")
        rec = gate.get(name)
        if not rec:
            warnings.append(f"skill {name}: has not passed the quality gate — python3 .tf/factory/skill_gate.py {name}")
        elif rec.get("fingerprint") != skill_fingerprint(s["_dir"]):
            warnings.append(f"skill {name}: changed after the last gate — python3 .tf/factory/skill_gate.py {name}")
        if s["_lines"] > 300:
            warnings.append(f"skill {name}: SKILL.md has {s['_lines']} lines — move details to references/")

    marked = {n for n, s in skills.items() if (s.get("metadata") or {}).get("visibility") == "name"}
    size = skill_listing(listing, lim.get("skill_listing_stack_slots", 6), marked,
                         tuple(cfg["skill_visibility"]["name_only_prefixes"]))
    if size > lim.get("skill_listing_max_chars", 10**9):
        warnings.append(f"the list of skills with a description in a typical project has ≈{size} characters (> {lim['skill_listing_max_chars']}): "
                        "skills with a description by .tf/factory/skill_profile.py + a reserve for detected technologies. Claude Code keeps the list "
                        "in ~1% of the context window and on overflow removes the descriptions of the least used skills — shorten descriptions, "
                        "move rarely needed skills to name-only (rules in skill_profile.py) or set "
                        "disable-model-invocation for skills run by hand (`/doctor` shows the cost)")
    for t, body in traits.items():
        if body.count("\n") + 1 > lim["trait_max_lines"]:
            errors.append(f"trait {t}: too long (> {lim['trait_max_lines']} lines) — traits are meant to be short")

    def check_skills(owner: str, names: list[str]):
        for s in names or []:
            if s not in skills:
                errors.append(f"{owner}: unknown skill '{s}'")

    def check_tools(owner: str, tools: list[str]):
        for t in tools or []:
            base = t.split("(")[0]
            if base not in KNOWN_TOOLS and not base.startswith("mcp__"):
                errors.append(f"{owner}: unknown tool '{t}'")

    for tier_owner, tier in [(f"role {n}", r.get("tier")) for n, r in roles.items()] + \
                            [(f"shared {n}", s.get("tier")) for n, s in cfg["shared_agents"].items()] + \
                            [(f"consultant {n}", s.get("tier", "std")) for n, s in cfg["consultants"].items()]:
        if tier not in cfg["tiers"]:
            errors.append(f"{tier_owner}: unknown tier '{tier}'")

    for n, r in roles.items():
        check_skills(f"role {n}", r.get("skills"))
        check_skills(f"role {n} (preload)", r.get("preload"))
        check_tools(f"role {n}", r.get("tools"))
        if r.get("grounding") not in (None, "sources-only"):
            errors.append(f"role {n}: grounding may only have the value 'sources-only'")
        if "Agent" in (r.get("tools") or []):
            warnings.append(f"role {n}: an executor with the Agent tool can nest subagents (cost)")
    for n, s in cfg["shared_agents"].items():
        check_skills(f"shared {n}", s.get("skills"))
        check_tools(f"shared {n}", s.get("tools"))
        for pn in s.get("only_for") or []:
            if pn not in personas_raw and pn != "@dispatcher" and s.get("_pack") in ("core", None):
                errors.append(f"shared {n}: only_for points to an unknown persona '{pn}'")
            elif pn not in personas_raw and pn != "@dispatcher":
                warnings.append(f"shared {n} ({s['_pack']}): only_for points to the persona '{pn}', which is not in the project")
    for n, c in cfg["consultants"].items():
        check_skills(f"consultant {n} ({c['_pack']})", c.get("skills"))
        if not c.get("description"):
            errors.append(f"consultant {n}: no description")
        if n in cfg["shared_agents"]:
            errors.append(f"consultant {n}: the same name as a shared agent")

    used = set()
    for pname, p in personas.items():
        for r in p.get("roles", []):
            if r not in roles:
                errors.append(f"persona {pname}: unknown role '{r}'")
            else:
                used.update(roles[r]["skills"])
        for t in p.get("traits", []):
            if t not in traits:
                errors.append(f"persona {pname}: unknown trait '{t}'")
        check_skills(f"persona {pname}", p.get("core_skills"))
        if p.get("isolation") not in (None, "worktree"):
            errors.append(f"persona {pname}: isolation may only have the value 'worktree'")
        for i, s in enumerate(p.get("scenarios") or []):
            if not (isinstance(s, dict) and s.get("situation") and s.get("behavior")):
                errors.append(f"persona {pname}: scenarios[{i}] needs the fields situation and behavior")
        check_skills(f"persona {pname} (methods)", p.get("methods"))
        check_skills(f"persona {pname} (stack)", p.get("stack"))
        check_skills(f"persona {pname} (skills)", p.get("skills"))
        check_skills(f"persona {pname} (drop_skills)", p.get("drop_skills"))
        for r, extra in (p.get("role_skills") or {}).items():
            if r not in p.get("roles", []):
                errors.append(f"persona {pname}: role_skills for the role '{r}', which the persona does not have")
            check_skills(f"persona {pname} (role_skills.{r})", extra)
        used.update((p.get("skills") or []) + (p.get("methods") or []) + (p.get("stack") or []) + (p.get("core_skills") or []))
        if not any(r in roles for r in p.get("roles", [])):
            continue
        used.update(persona_skills(p, roles, cfg))
        if not p.get("priorities"):
            errors.append(f"persona {pname}: no priorities (needed to settle conflicts)")
    for s in [*cfg["shared_agents"].values(), *cfg["consultants"].values()]:
        used.update(s.get("skills") or [])
    used.update(cfg.get("always_skills") or [])
    e, w = skill_usage(skills, used, cfg)
    errors += e
    warnings += w
    for hit in inactive_mentions(inactive_skills(skills), active_texts() if inactive_skills(skills) else {}):
        warnings.append(f"{hit} — a reference to a disabled skill (the Skill tool will not load it); keep the topic, "
                        "remove the name or point to an active skill")

    if not errors:
        rendered = render_all()
        names = [re.search(r"^name: (.+)$", t, re.M).group(1) for t in rendered.values()]
        for rel, t in rendered.items():
            if not t.startswith("---\n"):
                errors.append(f"{rel}: the frontmatter must start on line 1 (otherwise Claude Code skips the file)")
        dup = {n for n in names if names.count(n) > 1}
        if dup:
            errors.append(f"duplicated agent names: {sorted(dup)}")
        desc_chars = sum(len(m.group(1)) for t in rendered.values()
                         for m in [re.search(r"^description: (.+)$", t, re.M)] if m)
        est = int(desc_chars / 3.5)
        hard = lim.get("agent_descriptions_hard_tokens", 15000)
        if est > hard:
            errors.append(f"agent descriptions ≈{est} tokens (> {hard}, the Claude Code limit) — shorten the descriptions or "
                          "install fewer packs")
        elif est > lim["agent_descriptions_max_tokens"]:
            warnings.append(f"agent descriptions ≈{est} tokens (> the reserve {lim['agent_descriptions_max_tokens']}) — every "
                            "pack adds personas and consultants; consider fewer packs or shorter descriptions")
        # stale files
        on_disk = {p.relative_to(OUT_DIR).as_posix(): p.read_text(encoding="utf-8")
                   for p in OUT_DIR.rglob("*.md")} if OUT_DIR.exists() else {}
        if on_disk != rendered:
            errors.append("files in .claude/agents/_generated are stale — run: python3 .tf/factory/build.py")
        if not CATALOG.exists() or CATALOG.read_text(encoding="utf-8") != render_catalog():
            errors.append(".claude/catalog.md is stale — run: python3 .tf/factory/build.py")
        stale = [p.relative_to(ROOT).as_posix() for p in reference_files()
                 if with_toc(p.read_text(encoding="utf-8")) != p.read_text(encoding="utf-8")]
        if stale:
            errors.append(f"a missing or stale table of contents in {len(stale)} reference files (e.g. {stale[0]}) — "
                          "run: python3 .tf/factory/build.py")
        for pname, p in personas.items():
            for x in p.get("extra_agents") or []:
                if not any(k == f"{x}.md" or k.endswith(f"/{x}.md") for k in rendered):   # flat in the plugin layout
                    errors.append(f"persona {pname}: extra_agents points to an unknown agent '{x}'")
    # Fixed sections of reference files in a fixed order (outside code blocks) — the rules are supplied by overlays
    # (`reference_sections` in pack.yaml, e.g. in pack-it: archetypes in the mapper style).
    for skill, rule in (cfg.get("reference_sections") or {}).items():
        ref_dir = SKILLS_DIR / skill / "references"
        required = rule.get("sections") or []
        for f in sorted(ref_dir.glob("*.md")) if ref_dir.exists() else []:
            if f.name in (rule.get("skip") or []):
                continue
            heads, fence = [], False
            for ln in f.read_text(encoding="utf-8").splitlines():
                if ln.startswith("```"):
                    fence = not fence
                elif not fence and ln.startswith("## "):
                    heads.append(ln[3:].strip())
            found = [h for h in heads if h in required]
            if found != required:
                missing = [h for h in required if h not in heads]
                errors.append(f"{skill}/references/{f.name}: fixed sections "
                              + (f"missing {missing}" if missing else "in the wrong order"))

    # factory version per SemVer 2.0.0 (.tf/factory/PUBLIC_API.md): VERSION, CHANGELOG order, bump kind since 1.35.0
    sv_path = SKILLS_DIR / "core-semver" / "scripts" / "semver.py"
    if sv_path.exists() and (FACTORY / "CHANGELOG.md").exists():
        import importlib.util
        spec = importlib.util.spec_from_file_location("ctf_semver", sv_path)
        sv = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(sv)
        version = (FACTORY / "VERSION").read_text(encoding="utf-8").strip() if (FACTORY / "VERSION").exists() else None
        if version:
            try:
                sv.Version(version)
            except ValueError as e:
                errors.append(f".tf/factory/VERSION: {e}")
        for p in sv.check_changelog((FACTORY / "CHANGELOG.md").read_text(encoding="utf-8"), version,
                                    cfg.get("semver_strict_from")):
            errors.append(f".tf/factory/CHANGELOG.md: {p}")
    errors += steps_errors(cfg)
    loop_skill = SKILLS_DIR / "tf-task" / "SKILL.md"
    if loop_skill.is_file() and cfg.get("steps"):
        errors += steps_table_errors(cfg, loop_skill.read_text(encoding="utf-8"))
    return errors, warnings


