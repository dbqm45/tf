def cmd_new_skill(name: str, description: str, role: str | None = None, name_only: bool = False):
    cfg = load_config()
    if not name.startswith(skill_prefixes(cfg)):
        print(f"✗ The name must start with a dimension prefix: {skill_prefixes(cfg)}")
        return 2
    d = SKILLS_DIR / name
    if d.exists():
        print(f"✗ The skill {name} already exists")
        return 2
    roles = load_dir("roles") if role else {}
    role_file = ROOT / roles[role]["_src"] if role in roles else None
    if role and not role_file:
        print(f"✗ There is no role {role} (.tf/config/roles/ nor .tf/factory/packs/*/roles/)")
        return 2
    tpl = (FACTORY / "templates" / "SKILL.template.md").read_text(encoding="utf-8")
    (d / "references").mkdir(parents=True)
    short = boundary(description)[0].strip()[:170].replace(": ", " — ")   # for the author to shorten
    body = (tpl.replace("{{name}}", name).replace("{{short}}", short)
            .replace("{{description}}", description.replace('"', "'")))
    facet = facet_of(name, cfg)
    if facet.get("contract"):
        rows = "\n".join(f"| **{v}** | … |" for v in cfg.get("vocabulary", []))
        body += (f"\n## Domain concepts in {name.split('-', 1)[1]}\n"
                 f"<!-- Contract: every vocabulary concept → this technology's idiom. Checked by `build.py check`. -->\n"
                 f"| Concept (vocabulary) | Idiom |\n|---|---|\n{rows}\n")
    import datetime as _dt
    fr = _freshness()
    due = fr.add_months(_dt.date.today(), fr.interval(name, fr.load_policy(ROOT))).isoformat()
    extra = f"  review: \"{due}\"\n  keywords: \"\"\n" + ("  visibility: name\n" if name_only else "")
    body = re.sub(r"^(  catalog: .*\n)", lambda m: m.group(1) + extra, body, count=1, flags=re.M)
    (d / "SKILL.md").write_text(body, encoding="utf-8")
    wired = ""
    if role_file:
        text = role_file.read_text(encoding="utf-8")
        m = re.search(r"^skills: \[(.*)\]$", text, re.M)
        if m:
            items = [x.strip() for x in m.group(1).split(",") if x.strip()]
            new_line = "skills: [" + ", ".join(items + [name]) + "]"
            role_file.write_text(text[:m.start()] + new_line + text[m.end():], encoding="utf-8")
            wired = f"✓ Added to {roles[role]['_src']} (skills)\n"
        else:
            wired = f"⚠ {roles[role]['_src']} has no \"skills: [...]\" list on one line — add {name} by hand\n"
    ev = evals_file(name)
    if not ev.exists():
        ev.parent.mkdir(parents=True, exist_ok=True)
        todo = {"skill": name, "scenarios": [
            {"id": "TODO-problem-1", "expect": "trigger",
             "prompt": "TODO: a real user question the model handles badly without the skill",
             "checks": {"all": [["TODO: a phrase of knowledge specific to the skill", "TODO: a synonym"],
                                ["TODO: a second, independent thing the answer must contain"]],
                        "none": ["TODO: a typical mistake the answer must not contain"]}},
            {"id": "TODO-problem-2", "expect": "trigger",
             "prompt": "TODO: the same area, other words (as a human asks, not as the skill description says)",
             "checks": {"all": [["TODO"], ["TODO"]]}},
            {"id": "TODO-neighbor", "expect": "no-trigger", "neighbor": "TODO-neighboring-skill-name",
             "prompt": "TODO: a borderline question that belongs to the neighboring skill"}]}
        ev.write_text(json.dumps(todo, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    rel = ev.relative_to(ROOT)
    print(wired + f"""✓ Created .claude/skills/{name}/SKILL.md (review date {due}) and the scenario skeleton {rel}
Next (the core-skill-authoring skill):
  1. FIRST the scenarios in {rel}: 2× trigger with a gap the model has without the skill, 1× no-trigger with a neighbor.
  2. Optionally a baseline: python3 {TESTS_REL}/run_skill_evals.py --skills {name} --models sonnet --baseline
  3. The SKILL.md content — the minimum that closes the gaps; details to references/.
  4. Add the skill to a role in .tf/config/roles/ and run python3 .tf/factory/build.py
  5. Gate: python3 .tf/factory/skill_gate.py {name}   (+ --model haiku,sonnet with a human's consent — paid)""")
    return 0


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "build"
    if cmd == "build":
        return cmd_build()
    if cmd == "check":
        return cmd_check()
    if cmd == "list":
        return cmd_list()
    if cmd == "managed-apply":   # the only command that sends agents to the account (ant apply); without --yes only the plan
        import target_managed  # noqa: E402
        return target_managed.apply(TARGETS["managed-agents"], yes="--yes" in argv[2:])
    if cmd == "new-skill" and len(argv) >= 4:
        rest = argv[4:]
        role = rest[rest.index("--role") + 1] if "--role" in rest and rest.index("--role") + 1 < len(rest) else None
        return cmd_new_skill(argv[2], argv[3], role=role, name_only="--name-only" in rest)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
