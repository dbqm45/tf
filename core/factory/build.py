TOC_MARKS = {"en": "> **Contents:**", "pl": "> **Spis treści:**"}   # marker in the file's language; both recognized
TOC_MARK = TOC_MARKS["pl"]
PL_LETTERS = set("ąćęłńóśźżĄĆĘŁŃÓŚŹŻ")


def text_language(text: str) -> str:
    """`pl` or `en` by the share of Polish letters outside code (the same rule as the skill gate, step 5)."""
    body = re.sub(r"```.*?```|`[^`\n]*`", " ", text, flags=re.S)
    letters = [c for c in body if c.isalpha()]
    return "pl" if letters and sum(c in PL_LETTERS for c in letters) / len(letters) >= 0.004 else "en"
TOC_MIN_LINES = 100   # Anthropic: a reference file > 100 lines has a table of contents (the model sometimes reads only the start)


def with_toc(text: str) -> str:
    """A reference file with an up-to-date table of contents (one line under the title) or unchanged when short."""
    lines = []
    for l in text.splitlines():
        if l.startswith(tuple(TOC_MARKS.values())):
            if lines and not lines[-1].strip():
                lines.pop()   # the empty line inserted together with the table of contents
            continue
        lines.append(l)
    body = "\n".join(lines)
    in_code, heads = False, []
    for l in lines:
        if l.startswith("```"):
            in_code = not in_code
        elif not in_code and l.startswith("## ") and l[3:].strip() not in ("Źródła", "Spis treści", "Sources", "Contents"):
            h = l[3:].strip()
            heads.append(h if len(h) <= 60 else h[:60].rsplit(" ", 1)[0] + "…")
    if len(lines) <= TOC_MIN_LINES or len(heads) < 3:
        return body + ("\n" if text.endswith("\n") else "")
    mark = TOC_MARKS[text_language(body)]
    toc = f"{mark} " + " · ".join(heads)
    i = next((k for k, l in enumerate(lines) if l.startswith("# ")), -1)
    out = lines[:i + 1] + ["", toc] + lines[i + 1:] if i >= 0 else [toc, ""] + lines
    # no double empty lines around the table of contents
    res = "\n".join(out).replace(f"\n\n\n{mark}", f"\n\n{mark}").replace(toc + "\n\n\n", toc + "\n\n")
    return res + "\n"


def inactive_mentions(inactive: set[str], texts: dict[str, str]) -> list[str]:
    """Mentions of disabled skills (whole word) as `file:line: name`. A pointer to a disabled skill tells
    the agent to load a skill the Skill tool will not load — the agent loses a turn or reads SKILL.md by hand."""
    if not inactive:
        return []
    pat = re.compile(r"(?<![\w-])(" + "|".join(map(re.escape, sorted(inactive))) + r")(?![\w-])")
    return [f"{rel}:{i}: {m.group(1)}" for rel, text in texts.items()
            for i, line in enumerate(text.splitlines(), 1) for m in pat.finditer(line)]


