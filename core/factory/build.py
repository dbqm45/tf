def skill_fingerprint(name: str) -> str:
    """Odcisk treści skilla do bramki jakości (.tf/factory/skill_gate.py): pliki skilla i jego scenariusze. Ścieżki względne,
    spis treści i ścieżki testów po instalacji normalizowane — ten sam skill ma ten sam odcisk w fabryce i w projekcie."""
    import hashlib
    h = hashlib.sha256()
    d = SKILLS_DIR / name
    files = [(p.relative_to(d).as_posix(), p) for p in sorted(d.rglob("*")) if p.is_file() and "__pycache__" not in p.parts]
    ev = evals_file(name)
    if ev.exists():
        files.append(("evals.json", ev))
    for rel, p in files:
        data = p.read_bytes()
        if p.suffix in (".md", ".json", ".yml"):
            text = data.decode("utf-8", errors="ignore").replace(" .claude/tests/test_", " tests/test_") \
                .replace("(python3 .claude/tests/", "(python3 tests/")
            if p.suffix == ".md" and rel.startswith("references/"):
                text = with_toc(text)
            if rel == "SKILL.md":   # termin przeglądu (.tf/factory/freshness.py) nie zmienia treści — bramka zostaje ważna
                text = re.sub(r"^  review:.*\n", "", text, count=1, flags=re.M)
            data = text.encode("utf-8")
        h.update(rel.encode() + b"\0" + data + b"\0")
    return h.hexdigest()[:16]


def check_review_date(name: str, meta: dict) -> tuple[list[str], list[str]]:
    """`metadata.review`: termin przeglądu skilla w formacie RRRR-MM-DD (.tf/factory/freshness.py)."""
    raw = meta.get("review")
    if raw is None:
        return [], [f"skill {name}: no metadata.review (the content review date) — "
                    f"python3 .tf/factory/freshness.py --reviewed {name}"]
    try:
        import datetime as _dt
        ok = re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(raw)) and _dt.date.fromisoformat(str(raw))
    except ValueError:
        ok = False
    if not ok:
        return [f"skill {name}: metadata.review '{raw}' is not a YYYY-MM-DD date"], []
    if not isinstance(raw, str):   # YAML zamienia RRRR-MM-DD bez cudzysłowu na datę; specyfikacja chce tekstu
        return [], [f"skill {name}: metadata.review without quotes — write review: \"{raw}\" (Agent Skills: metadata is text)"]
    return [], []


