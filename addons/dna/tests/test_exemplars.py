#!/usr/bin/env python3
"""Tests of exemplar files (lib/exemplars.py) and out/exemplars.md. python3 addons/dna/tests/test_exemplars.py"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ADDON = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ADDON))
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.dont_write_bytecode = True

import dna  # noqa: E402
from lib import code, detect, exemplars, verify  # noqa: E402
from test_dna import repo  # noqa: E402

BODY = "export function {n}() {{\n  const x = 1;\n  return x;\n}}\n"


def commit(root: Path, paths: list[str], when: str):
    env = {**os.environ, "GIT_AUTHOR_DATE": when, "GIT_COMMITTER_DATE": when}
    subprocess.run(["git", "add", *paths], cwd=root, check=True, env=env)
    subprocess.run(["git", "-c", "user.email=t@t", "-c", "user.name=t", "commit", "-q", "-m", "c"], cwd=root, check=True,
                   env=env)


def project() -> Path:
    files = {
        "src/components/OldList.tsx": BODY.format(n="OldList"),
        "src/components/Card.tsx": BODY.format(n="Card"),
        "src/components/Huge.tsx": BODY.format(n="Huge") + "// pad\n" * 400,
        "src/components/Tiny.tsx": "export const Tiny = 1;\n",
        "src/components/UsesOld.tsx": "/**\n * @deprecated\n */\nexport function Gone() {}\n",
        "src/components/legacy/Fresh.tsx": BODY.format(n="Fresh"),
        "src/components/Gen.tsx": "// @generated by tool\n" + BODY.format(n="Gen"),
        "src/components/Card.test.tsx": "import { Card } from './Card';\ntest('x', () => {});\n",
        "tsconfig.json": '{"compilerOptions": {"paths": {"@/*": ["./src/*"]}}, // comment\n}',
        "src/pages/Orders.tsx": "import { Card } from '@/components/Card';\n" + BODY.format(n="Orders"),
        "src/hooks/useOrders.ts": BODY.format(n="useOrders"),
        "src/pages/Signup.tsx": "export const Signup = () => <form onSubmit={go}></form>;\n",
        "api/routes/orders.py": "@router.get('/orders')\ndef list_orders():\n    return []\n",
        "api/services/billing.py": "def charge():\n    return 1\n",
    }
    root = repo(files)
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    commit(root, ["src/components/OldList.tsx"], "2023-01-01T10:00:00")
    commit(root, ["."], "2026-11-01T10:00:00")
    return root


def test_choice_per_kind_and_related_files():
    root = project()
    items = detect.detect(root, ADDON / "registry")["items"]
    items += code.ui(root, items, {})[0]
    ex = {e["data"]["change_type"]: e for e in exemplars.exemplars(root, items)[0]}
    comp = ex["component"]["data"]
    assert comp["path"] == "src/components/Card.tsx", comp            # recent, typical; not legacy/generated/huge/old
    assert comp["related"]["tests"] == ["src/components/Card.test.tsx"]
    assert comp["related"]["used_by"] == ["src/components/Card.test.tsx", "src/pages/Orders.tsx"]
    assert ex["page"]["data"]["path"] == "src/pages/Orders.tsx"
    assert ex["page"]["data"]["related"]["imports"] == ["src/components/Card.tsx"]
    assert ex["form"]["data"]["path"] == "src/pages/Signup.tsx"
    assert ex["hook"]["data"]["path"] == "src/hooks/useOrders.ts"
    assert ex["api-endpoint"]["data"]["path"] == "api/routes/orders.py"
    assert ex["service"]["data"]["path"] == "api/services/billing.py"
    assert ex["test"]["data"]["path"] == "src/components/Card.test.tsx"


def test_output():
    root = project()
    out = root / "out"
    assert dna.cmd_learn(root, out, online=False, cache=root / "cache") == 0
    assert verify.check_out(out, root) == []
    md = (out / "exemplars.md").read_text(encoding="utf-8")
    assert "| component | `src/components/Card.tsx` | src/components/Card.test.tsx |" in md
    assert "follow the exemplar" in (out / "INDEX.md").read_text(encoding="utf-8")


def main() -> int:
    tests = [(n, f) for n, f in sorted(globals().items()) if n.startswith("test_") and callable(f)]
    fails = 0
    for name, fn in tests:
        try:
            fn()
            print(f"✓ {name}")
        except Exception as e:  # noqa: BLE001
            fails += 1
            print(f"✗ {name}: {type(e).__name__}: {e}")
    print(f"\n{len(tests) - fails}/{len(tests)} passed")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
