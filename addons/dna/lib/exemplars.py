"""Exemplar files per kind of change: the file an agent follows when it writes a new page, component, hook, form,
endpoint, service, test or migration. No model.

Kinds come from paths and content (KINDS below). Per kind the candidates are scored:
  - recent: the last commit touching the file (git; without git, the file's mtime) — newer is better;
  - typical: size within the middle half of the kind's sizes (not the biggest, not a stub);
  - clean: not generated, not under legacy/old/deprecated directories, not importing a deprecated component.
The chosen file comes with its related files: its test, the local files it imports, the files that use it.
"""
from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path

from .code import CODE_EXT, _files, _read, _resolve, is_local
from .detect import SKIP_DIRS

BACKEND_EXT = (".py", ".java", ".kt", ".go", ".cs", ".rb", ".php", ".ts", ".js")
TEST = re.compile(r"(\.(test|spec)\.[jt]sx?$|(^|/)test_[^/]+\.py$|_test\.(py|go)$|Tests?\.(java|kt|cs)$)")
LEGACY = re.compile(r"(^|/)(legacy|old|deprecated|archive|__generated__|generated|gen)(/|$)", re.I)
GENERATED = re.compile(r"(@generated|auto-?generated|do not edit|generated by)", re.I)
KINDS = [  # (kind, path regex, content regex or None) — first match wins, tests first
    ("test", TEST, None),
    ("migration", re.compile(r"(^|/)(migrations?|db/migrate|alembic/versions)/"), None),
    ("form", re.compile(r"\.(tsx|jsx|vue|svelte)$"), re.compile(r"<form\b|useForm\(|<Formik\b|createForm\(")),
    ("page", re.compile(r"(^|/)(pages|app|screens|views|routes)/.*\.(tsx|jsx|vue|svelte)$"), None),
    ("hook", re.compile(r"(^|/)use(?:[A-Z][A-Za-z0-9]*|-[a-z][a-z0-9-]*)\.(ts|tsx|js|jsx)$"), None),
    ("component", re.compile(r"(^|/)components?/.*\.(tsx|jsx|vue|svelte)$"), None),
    ("store", re.compile(r"(^|/)(store|stores|slices|redux|state)/.*\.(ts|tsx|js)$"), None),
    ("api-endpoint", re.compile(r"(^|/)(controllers?|handlers?|routes?|api|endpoints?|routers?)/"),
     re.compile(r"@(Rest)?Controller|@(Get|Post|Put|Delete)Mapping|router\.(get|post|put|delete)\(|"
                r"app\.(get|post|put|delete)\(|@app\.(get|post|route)|@router\.(get|post)|func \w+\(w http\.")),
    ("service", re.compile(r"(^|/)services?/"), None),
]
EXT_OK = tuple(set(CODE_EXT) | set(BACKEND_EXT))


def _last_change(root: Path) -> dict[str, int]:
    try:
        r = subprocess.run(["git", "log", "-n", "3000", "--format=@%ct", "--name-only"], cwd=root, capture_output=True,
                           text=True, encoding="utf-8", errors="replace", timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return {}
    seen: dict[str, int] = {}
    ts = 0
    for ln in r.stdout.splitlines() if r.returncode == 0 else []:
        if ln.startswith("@"):
            ts = int(ln[1:] or 0)
        elif ln.strip() and ln not in seen:
            seen[ln] = ts
    return seen


def _kind(rel: str, text: str) -> str | None:
    for kind, path_rx, content_rx in KINDS:
        if path_rx.search(rel) and (content_rx is None or content_rx.search(text)):
            return kind
    return None


def _test_of(root: Path, rel: str, tests: set[str]) -> list[str]:
    stem = Path(rel).name.split(".")[0]
    near = [t for t in tests if Path(t).name.split(".")[0] in (stem, f"test_{stem}", f"{stem}_test", f"{stem}Test")]
    return sorted(near, key=lambda t: (Path(t).parent != Path(rel).parent, t))[:2]


def forbidden_imports(decisions: list[dict] | None) -> list[str]:
    """Modules the agreed rules forbid (decisions of other add-ons with data.forbidden_import)."""
    return [d["data"]["forbidden_import"] for d in decisions or [] if (d.get("data") or {}).get("forbidden_import")]


def exemplars(root: Path, items: list[dict], decisions: list[dict] | None = None) -> tuple[list[dict], dict]:
    deprecated = {i["data"]["name"] for i in items if (i.get("data") or {}).get("deprecated")}
    forbidden = forbidden_imports(decisions)
    code, _styles, _tokens = _files(root)
    extra = []
    for dirpath, dirnames, filenames in os.walk(root):   # backend files the UI walk does not collect
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for n in filenames:
            if n.endswith((".py", ".java", ".kt", ".go", ".cs", ".rb", ".php")) and len(extra) < 4000:
                extra.append(Path(dirpath) / n)
    files = list(dict.fromkeys(code + extra))
    changed = _last_change(root)
    texts = {f: _read(f) for f in files}
    rel = {f: f.relative_to(root).as_posix() for f in files}
    tests = {rel[f] for f in files if TEST.search(rel[f])}
    by_kind: dict[str, list[Path]] = {}
    for f in files:
        k = _kind(rel[f], texts[f])
        if k:
            by_kind.setdefault(k, []).append(f)
    importers: dict[str, set[str]] = {}
    for f in files:
        for m in re.finditer(r"""from\s+['"]([^'"]+)['"]|require\(['"]([^'"]+)['"]\)""", texts[f]):
            spec = m.group(1) or m.group(2)
            if not is_local(spec, root):
                continue
            target = _resolve(f, spec, root)
            if target and target in rel:
                importers.setdefault(rel[target], set()).add(rel[f])
    out = []
    for kind, fs in sorted(by_kind.items()):
        sizes = sorted(len(texts[f]) for f in fs)
        lo, hi = sizes[len(sizes) // 4], sizes[(3 * len(sizes)) // 4] if len(sizes) > 1 else sizes[0]
        scored = []
        for f in fs:
            r, text = rel[f], texts[f]
            if LEGACY.search(r) or GENERATED.search(text[:400]):
                continue
            if any(re.search(rf"\b{re.escape(d)}\b", text) for d in deprecated):
                continue
            if any(re.search(rf"""from\s+['"]{re.escape(m)}(/[^'"]*)?['"]|require\(['"]{re.escape(m)}['"]""", text)
                   for m in forbidden):
                continue   # an agreed rule forbids an import it uses
            when = changed.get(r) or int(f.stat().st_mtime)
            typical = lo <= len(text) <= hi
            scored.append(((typical, when), f))
        if not scored:
            continue
        scored.sort(key=lambda x: x[0], reverse=True)
        best = scored[0][1]
        r = rel[best]
        local = []
        for m in re.finditer(r"""from\s+['"]([^'"]+)['"]""", texts[best]):
            if not is_local(m.group(1), root):
                continue
            t = _resolve(best, m.group(1), root)
            if t and t in rel and rel[t] not in local:
                local.append(rel[t])
        related = {"tests": _test_of(root, r, tests) if kind != "test" else [],
                   "imports": local[:5], "used_by": sorted(importers.get(r, set()))[:3]}
        when = changed.get(r)
        out.append({"id": f"E-{kind}", "kind": "exemplar", "title": f"{kind}: {r}", "scope": {"paths": ["**"]},
                    "status": "auto-accepted",
                    "acceptance": f"best of {len(scored)}: " + ("recent, typical size" if scored[0][0][0] else "recent"),
                    "data": {"topic": "exemplar", "change_type": kind, "path": r, "related": related,
                             "candidates": len(scored), "last_commit": when},
                    "evidence": [f"{r}:1"]})
    return out, {"read": [f"{len(files)} files for exemplars"], "skipped": []}
