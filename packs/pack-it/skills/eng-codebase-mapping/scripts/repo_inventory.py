#!/usr/bin/env python3
"""
Spis repozytorium przed analizą modelem (rekonstrukcja projektu, mapa kodu): języki, pliki budowania, wykluczenia
(zależności, wynik budowania, kod wygenerowany), moduły i partie plików według budżetu tokenów. Tylko biblioteka
standardowa; kodu nie uruchamia, plików nie zmienia.

  python3 repo_inventory.py <repo>                        # tekst: języki, moduły, partie
  python3 repo_inventory.py <repo> --json                 # pełny wynik
  python3 repo_inventory.py <repo> --budget-tokens 60000  # budżet jednej partii (domyślnie 60000; tokeny ≈ bajty / 4)

Partia = pliki produkcyjne jednego modułu (katalogu z plikiem budowania) albo jego podkatalogu, gdy moduł przekracza
budżet; pliki spoza modułów trafiają do partii katalogów najwyższego poziomu. Testy są liczone, ale bez partii.
"""
from __future__ import annotations

import collections
import json
import os
import re
import sys

LANG = {".py": "Python", ".ts": "TypeScript", ".tsx": "TypeScript", ".js": "JavaScript", ".jsx": "JavaScript",
        ".mjs": "JavaScript", ".cjs": "JavaScript", ".java": "Java", ".kt": "Kotlin", ".cs": "C#", ".go": "Go",
        ".rb": "Ruby", ".rs": "Rust", ".scala": "Scala", ".swift": "Swift", ".c": "C", ".h": "C", ".cpp": "C++",
        ".hpp": "C++", ".sql": "SQL", ".vue": "Vue", ".svelte": "Svelte"}
BUILD = {"pom.xml": "maven", "build.gradle": "gradle", "build.gradle.kts": "gradle", "settings.gradle": "gradle",
         "package.json": "npm", "go.mod": "go", "pyproject.toml": "python", "setup.py": "python",
         "requirements.txt": "python", "Cargo.toml": "cargo", "Gemfile": "ruby", "build.sbt": "sbt"}
BUILD_EXT = {".csproj": "dotnet", ".sln": "dotnet", ".fsproj": "dotnet"}
DEPS = {"node_modules", "vendor", "bower_components", ".venv", "venv", "packages"}   # packages: NuGet/.NET
BUILD_OUT = {"dist", "build", "target", "out", "bin", "obj", ".next", ".nuxt", "coverage", "__pycache__"}
GENERATED = re.compile(r"(\.pb\.go|_pb2\.py|\.g\.cs|\.designer\.cs|\.generated\.\w+|\.min\.js|\.min\.css)$", re.I)
GEN_HEADER = re.compile(r"(Code generated .* DO NOT EDIT|<auto-generated|@generated)", re.I)
TEST = re.compile(r"(^|/)(tests?|__tests__|e2e|fixtures|spec)/|\.(test|spec)\.|(^|/)test_[^/]*\.py$|_test\.(py|go)$|"
                  r"\.Tests?/|(Test|Tests|IT)\.java$|Tests?\.cs$")


def tokens(nbytes: int) -> int:
    return (nbytes + 3) // 4


def scan(root: str):
    files, excluded, build = [], [], []
    for dp, dn, fn in os.walk(root):
        rel_dir = os.path.relpath(dp, root).replace(os.sep, "/")
        rel_dir = "" if rel_dir == "." else rel_dir
        keep = []
        for d in sorted(dn):
            p = f"{rel_dir}/{d}".lstrip("/")
            if d.startswith(".") and d not in (".github",):
                continue
            # `packages` to zależności tylko w projekcie .NET; w monorepo JS to katalog pakietów
            if d in DEPS and not (d == "packages" and not any(f.endswith(".sln") for f in fn)):
                excluded.append({"path": p, "reason": "zależności"})
            elif d in BUILD_OUT:
                excluded.append({"path": p, "reason": "wynik budowania"})
            else:
                keep.append(d)
        dn[:] = keep
        for f in sorted(fn):
            p = f"{rel_dir}/{f}".lstrip("/")
            kind = BUILD.get(f) or BUILD_EXT.get(os.path.splitext(f)[1])
            if kind:
                build.append({"file": p, "kind": kind})
            ext = os.path.splitext(f)[1].lower()
            if ext not in LANG:
                continue
            full = os.path.join(dp, f)
            try:
                size = os.path.getsize(full)
                with open(full, encoding="utf-8", errors="replace") as fh:
                    head = fh.read(400)
            except OSError:
                continue
            if GENERATED.search(f) or GEN_HEADER.search(head):
                excluded.append({"path": p, "reason": "wygenerowany"})
                continue
            files.append({"path": p, "language": LANG[ext], "bytes": size, "test": bool(TEST.search(p))})
    return files, excluded, build


def module_of(path: str, mod_dirs: list[str]) -> str | None:
    for m in mod_dirs:   # najdłuższy pasujący katalog modułu
        if m and (path == m or path.startswith(m + "/")):
            return m
    return None


def split(name: str, files: list[dict], budget: int, depth: int = 0) -> list[dict]:
    total = sum(tokens(f["bytes"]) for f in files)
    if total <= budget or len(files) == 1:
        return [{"name": name or ".", "files": [f["path"] for f in files], "tokens": total}]
    prefix = (name + "/") if name else ""
    sub = collections.defaultdict(list)
    for f in files:
        rest = f["path"][len(prefix):]
        sub[rest.split("/")[0] if "/" in rest else ""].append(f)
    if len(sub) == 1 and "" not in sub:      # jeden podkatalog — schodzimy niżej bez tworzenia partii
        only = next(iter(sub))
        return split(prefix + only, files, budget, depth + 1)
    out, loose = [], sub.pop("", [])
    for d in sorted(sub):
        out += split(prefix + d, sub[d], budget, depth + 1)
    if loose:   # pliki leżące bezpośrednio w katalogu: łącz po kolei do budżetu
        cur, cur_t = [], 0
        for f in loose:
            t = tokens(f["bytes"])
            if cur and cur_t + t > budget:
                out.append({"name": f"{name or '.'} (pliki)", "files": cur, "tokens": cur_t})
                cur, cur_t = [], 0
            cur.append(f["path"])
            cur_t += t
        out.append({"name": f"{name or '.'} (pliki)", "files": cur, "tokens": cur_t})
    return out


def inventory(root: str, budget: int) -> dict:
    files, excluded, build = scan(root)
    mod_dirs = sorted({os.path.dirname(b["file"]) for b in build}, key=lambda d: (-d.count("/"), d))
    langs = collections.defaultdict(lambda: {"files": 0, "test_files": 0, "tokens": 0})
    for f in files:
        x = langs[f["language"]]
        x["test_files" if f["test"] else "files"] += 1
        x["tokens"] += tokens(f["bytes"])
    prod = [f for f in files if not f["test"]]
    by_mod = collections.defaultdict(list)
    for f in prod:
        m = module_of(f["path"], mod_dirs)
        by_mod[m if m is not None else (f["path"].split("/")[0] if "/" in f["path"] else "")].append(f)
    batches = []
    for name in sorted(by_mod):
        batches += split(name, by_mod[name], budget)
    modules = [{"path": m or ".", "build": sorted(b["kind"] for b in build if os.path.dirname(b["file"]) == m),
                "files": len(by_mod.get(m, [])), "tokens": sum(tokens(f["bytes"]) for f in by_mod.get(m, []))}
               for m in sorted(set(mod_dirs))]
    return {"root": os.path.abspath(root), "budget_tokens": budget,
            "languages": sorted(({"language": k, **v} for k, v in langs.items()), key=lambda x: -x["tokens"]),
            "build_files": build, "modules": modules, "excluded": excluded, "batches": batches,
            "totals": {"files": len(prod), "test_files": len(files) - len(prod),
                       "tokens": sum(tokens(f["bytes"]) for f in prod), "batches": len(batches)}}


def render(r: dict) -> str:
    t = r["totals"]
    L = [f"Pliki produkcyjne: {t['files']} (~{t['tokens']} tokenów), testy: {t['test_files']}, partie: {t['batches']} "
         f"(budżet {r['budget_tokens']})", "Języki (pliki, testy, tokeny):"]
    L += [f"  - {x['language']}: {x['files']}, {x['test_files']}, ~{x['tokens']}" for x in r["languages"]]
    L.append("Pliki budowania: " + (", ".join(f"{b['file']} ({b['kind']})" for b in r["build_files"]) or "brak"))
    if r["excluded"]:
        by = collections.Counter(e["reason"] for e in r["excluded"])
        L.append("Wykluczone: " + ", ".join(f"{k} {v}" for k, v in sorted(by.items())))
    L.append("Partie (nazwa, pliki, tokeny):")
    L += [f"  - {b['name']}: {len(b['files'])}, ~{b['tokens']}" for b in r["batches"]]
    return "\n".join(L)


def main(argv: list[str]) -> int:
    args, budget, as_json = [], 60000, False
    it = iter(argv)
    for a in it:
        if a == "--json":
            as_json = True
        elif a == "--budget-tokens":
            budget = int(next(it, "60000"))
        elif a in ("-h", "--help"):
            print(__doc__)
            return 0
        else:
            args.append(a)
    if len(args) != 1 or not os.path.isdir(args[0]):
        print(f"✗ podaj katalog repozytorium (jest: {args})", file=sys.stderr)
        return 2
    r = inventory(args[0], budget)
    print(json.dumps(r, ensure_ascii=False, indent=2) if as_json else render(r))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
