#!/usr/bin/env python3
"""
Moduł `tech-debt` tf analyze, piętro 0 (bez modelu i sieci): widoczne ślady długu technicznego (eng-tech-debt-audit).

  python3 scan.py --root <repo> [--files a,b]     # JSON Lines na stdout (kontrakt: .tf/factory/analyze.py)

Reguły:
- `marker-without-ticket` — TODO/FIXME/HACK/XXX w komentarzu bez odwołania do zgłoszenia (`#123`, `ABC-123`, URL);
  w repozytorium git wiek linii z `git blame` trafia do dowodu, a znacznik starszy niż 180 dni ma wagę średnią;
- `skipped-test` — pominięty test (`it/test/describe.skip`, `xit`, `xdescribe`, `@pytest.mark.skip`, `@Disabled`,
  `@Ignore`) bez powodu: bez argumentu z powodem, bez zgłoszenia w linii i bez komentarza w linii wyżej; liczy się
  tylko początek linii (napis w kodzie testu to nie pominięcie);
- `suppressed-check` — `@ts-ignore`, `eslint-disable…` bez ` -- powód`, gołe `# noqa` i `# type: ignore` bez kodu;
- `large-file` — plik kodu powyżej 1000 linii (bez wygenerowanych: „generated”, „DO NOT EDIT” w nagłówku).
Martwy kod (wymaga grafu wywołań) i przestarzałe zależności (wymagają sieci) to kolejne piętro. Znalezienie =
„sprawdź i zdecyduj: naprawić, opisać zgłoszeniem albo usunąć”. Dokumentacja i fixtures są pomijane. Tylko
biblioteka standardowa.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

for _stream in (sys.stdout, sys.stderr):  # Windows: strona kodowa (cp1250) nie zna „✓”, „⚠” — zawsze UTF-8
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

SKIP_DIRS = {"node_modules", ".git", "dist", "build", "coverage", ".venv", "venv", "__pycache__", ".tf", ".next",
             "target", "_vendor", "vendor", "third_party"}
FACTORY_OWNED = (".tf/factory/", ".claude/")
DOC_OR_FIXTURE = re.compile(r"(^|/)(fixtures|examples?|docs?|testdata|__snapshots__)/|\.(md|mdx|rst|txt|adoc)$")
HASH_COMMENT = {".py", ".rb", ".sh", ".bash", ".pl", ".r"}
CODE_EXT = {".py", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".java", ".kt", ".go", ".cs", ".rb", ".php", ".rs",
            ".swift", ".scala", ".c", ".cc", ".cpp", ".h", ".hpp", ".vue", ".svelte", ".sh", ".dart"}
LARGE = 1000
OLD_DAYS = 180

MARKER = re.compile(r"\b(TODO|FIXME|HACK|XXX)\b")
TICKET = re.compile(r"#\d+|\b[A-Z][A-Z0-9]+-\d+\b|https?://")
STRING = re.compile(r"\"(?:[^\"\\\n]|\\.)*\"|'(?:[^'\\\n]|\\.)*'|`(?:[^`\\\n]|\\.)*`")
SKIP_JS = re.compile(r"^\s*(?:(?:it|test|describe|context)\.skip|x(?:it|describe|test))\s*\(")
SKIP_ANNOT = re.compile(r"^\s*@(?:pytest\.mark\.skip|Disabled|Ignore)\b(?!If|_if)(?:\s*\(\s*\))?(?!\s*\()")
GENERATED = re.compile(r"DO NOT EDIT|@generated|\bcode generated\b|\bauto-?generated\b|this file (is|was) generated|"
                       r"generated by\b", re.I)


def comment_part(line: str, ext: str) -> str:
    """Treść komentarza w linii (po usunięciu napisów), albo pusty napis."""
    code = STRING.sub('""', line)
    if ext in HASH_COMMENT:
        i = code.find("#")
        return code[i:] if i >= 0 else ""
    s = code.lstrip()
    if s.startswith(("*", "/*", "<!--")):
        return s
    for tok in ("//", "/*"):
        i = code.find(tok)
        if i >= 0:
            return code[i:]
    return ""


def emit(rule: str, rel: str, line: int, snippet: str, title: str, severity: str, evidence: str,
         suggestion: str, confidence: float = 0.8) -> None:
    print(json.dumps({"rule": rule, "title": title, "file": rel, "line": line, "snippet": snippet.strip()[:160],
                      "severity": severity, "confidence": confidence, "evidence": evidence,
                      "basis": "eng-tech-debt-audit (dług jawny i ukryty), qa-regression (pominięte testy)",
                      "suggestion": suggestion}, ensure_ascii=False))


def blame_ages(root: Path, rel: str) -> dict[int, int]:
    """Wiek linii w dniach z `git blame` (pusty słownik poza repozytorium git)."""
    r = subprocess.run(["git", "blame", "--line-porcelain", "--", rel], cwd=root, capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    if r.returncode != 0:
        return {}
    ages, now, line_no = {}, time.time(), 0
    for row in r.stdout.splitlines():
        m = re.match(r"^[0-9a-f]{40} \d+ (\d+)", row)
        if m:
            line_no = int(m.group(1))
        elif row.startswith("committer-time "):
            ages[line_no] = int((now - int(row.split()[1])) // 86400)
    return ages


def in_multiline_string(lines: list[str], ext: str) -> set[int]:
    """Indeksy linii wewnątrz wieloliniowych napisów (Python `\"\"\"`/`'''`, szablony JS w odwrotnych apostrofach)."""
    inside, out, delim = False, set(), None
    for i, line in enumerate(lines):
        if inside:
            out.add(i)
        for tok in re.findall(r'\"\"\"|\'\'\'' if ext == ".py" else r"`", line):
            if not inside:
                inside, delim = True, tok
            elif tok == delim:
                inside = False
    return out


def scan_file(root: Path, rel: str, text: str, git: bool) -> None:
    ext = Path(rel).suffix.lower()
    lines = text.splitlines()
    strings = in_multiline_string(lines, ext) if ext in (".py", ".js", ".ts", ".jsx", ".tsx", ".mjs") else set()
    ages: dict[int, int] | None = None
    for i, line in enumerate(lines):
        com = "" if i in strings else comment_part(line, ext)
        if com:
            m = MARKER.search(com)
            if m and not TICKET.search(com):
                if ages is None:
                    ages = blame_ages(root, rel) if git else {}
                age = ages.get(i + 1)
                sev = "średnia" if age is not None and age > OLD_DAYS else "niska"
                emit("marker-without-ticket", rel, i + 1, line, f"{m.group(1)} bez zgłoszenia", sev,
                     f"znacznik w komentarzu bez odwołania do zgłoszenia"
                     + (f"; wiek linii {age} dni (git blame)" if age is not None else ""),
                     "załóż zgłoszenie i dopisz jego numer (np. `TODO(#123)`) albo napraw i usuń znacznik")
            sup = None
            if "@ts-ignore" in com:
                sup = "@ts-ignore"
            elif "eslint-disable" in com and "--" not in com.split("eslint-disable", 1)[1]:
                sup = "eslint-disable bez powodu"
            elif ext == ".py" and re.search(r"#\s*type:\s*ignore(?!\[)", com):
                sup = "type: ignore bez kodu"
            elif ext == ".py" and re.search(r"#\s*noqa(?!\s*:)", com, re.I):
                sup = "noqa bez kodu"
            if sup:
                emit("suppressed-check", rel, i + 1, line, f"wyciszone sprawdzenie: {sup}", "niska",
                     "wyciszenie bez zawężenia albo bez powodu ukrywa też przyszłe błędy",
                     "zawęź wyciszenie (`@ts-expect-error`, kod reguły w `noqa:`/`type: ignore[…]`, reguła w "
                     "`eslint-disable`) i dopisz powód po ` -- `")
        if SKIP_JS.match(line) or SKIP_ANNOT.match(line):
            prev = lines[i - 1].strip() if i else ""
            has_reason = TICKET.search(line) or prev.startswith(("//", "#", "/*", "*"))
            if not has_reason:
                emit("skipped-test", rel, i + 1, line, "pominięty test bez powodu", "średnia",
                     "test wyłączony bez powodu i bez zgłoszenia — regresja w tym miejscu przejdzie niezauważona",
                     "napraw test albo zostaw powód ze zgłoszeniem (`reason=…`, `@Disabled(\"#123 …\")`, komentarz)")
    if ext in CODE_EXT and len(lines) > LARGE and not GENERATED.search("\n".join(lines[:5])):
        emit("large-file", rel, 1, lines[0] if lines else "", f"plik ma {len(lines)} linii", "niska",
             f"{len(lines)} linii (próg {LARGE})", "podziel według odpowiedzialności (eng-module-depth, "
             "eng-refactor-planning); najpierw testy charakteryzujące", confidence=0.6)


def list_files(root: Path) -> tuple[list[str], bool]:
    top = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=root, capture_output=True, text=True,
                         encoding="utf-8", errors="replace")
    if top.returncode == 0 and Path(top.stdout.strip()).resolve() == root.resolve():
        r = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, encoding="utf-8",
                           errors="replace")
        return [f for f in r.stdout.splitlines() if f and not set(Path(f).parts) & SKIP_DIRS
                and not f.startswith(FACTORY_OWNED)], True
    out = []
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in SKIP_DIRS]
        out += [str((Path(dp) / f).relative_to(root)) for f in fns]
    return sorted(out), False


def scan(root: Path, files: list[str], git: bool) -> None:
    for rel in files:
        rel = rel.replace(os.sep, "/")
        p = root / rel
        if DOC_OR_FIXTURE.search(rel) or p.suffix.lower() not in CODE_EXT or not p.is_file() \
                or p.stat().st_size > 2_000_000 or ".min." in p.name:
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        scan_file(root, rel, text, git)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--files", default="")
    a = ap.parse_args()
    root = Path(a.root)
    listed, git = list_files(root)
    files = [f for f in a.files.split(",") if f] or listed
    scan(root, files, git)
    return 0


if __name__ == "__main__":
    sys.exit(main())
