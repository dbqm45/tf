#!/usr/bin/env python3
"""
The `tech-debt` module of tf analyze, tier 0 (no model and no network): visible traces of technical debt (eng-tech-debt-audit).

  python3 scan.py --root <repo> [--files a,b]     # JSON Lines on stdout (contract: .tf/factory/analyze.py)

Rules:
- `marker-without-ticket` — TODO/FIXME/HACK/XXX in a comment without a reference to a ticket (`#123`, `ABC-123`, URL);
  in a git repository the line's age from `git blame` goes into the evidence, and a marker older than 180 days has medium severity;
- `skipped-test` — a skipped test (`it/test/describe.skip`, `xit`, `xdescribe`, `@pytest.mark.skip`, `@Disabled`,
  `@Ignore`) without a reason: without an argument with a reason, without a ticket on the line and without a comment on the line above; only
  the start of the line counts (a string in the test code is not a skip);
- `suppressed-check` — `@ts-ignore`, `eslint-disable…` without ` -- reason`, bare `# noqa` and `# type: ignore` without a code;
- `large-file` — a code file over 1000 lines (except generated ones: "generated", "DO NOT EDIT" in the header).
Dead code (needs a call graph) and outdated dependencies (need the network) are the next tier. A finding =
"check it and decide: fix it, describe it in a ticket or remove it". Documentation and fixtures are skipped. Standard
library only.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

for _stream in (sys.stdout, sys.stderr):  # Windows: the code page (cp1250) has no "✓", "⚠" — always UTF-8
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

SKIP_DIRS = {"node_modules", ".git", "dist", "build", "coverage", ".venv", "venv", "__pycache__", ".tf", ".next",
             "target", "_vendor", "vendor", "third_party"}
FACTORY_OWNED = (".tf/factory/", ".claude/")
DOC_OR_FIXTURE = re.compile(r"(^|/)(fixtures|examples?|docs?|testdata|__snapshots__)/|\.(md|mdx|rst|txt|adoc)$")
HASH_COMMENT = {".py", ".rb", ".sh", ".bash", ".pl", ".r"}
CODE_EXT = {".py", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".java", ".kt", ".go", ".cs", ".rb", ".php", ".rs",
            ".swift", ".scala", ".c", ".cc", ".cpp", ".h", ".hpp", ".vue", ".svelte", ".sh", ".dart"}
LARGE = 1000
OLD_DAYS = 180

MARKER = re.compile(r"\b(TODO|FIXME|HACK|XXX)\b")
TICKET = re.compile(r"#\d+|\b[A-Z][A-Z0-9]+-\d+\b|https?://")
STRING = re.compile(r"\"(?:[^\"\\\n]|\\.)*\"|'(?:[^'\\\n]|\\.)*'|`(?:[^`\\\n]|\\.)*`")
SKIP_JS = re.compile(r"^\s*(?:(?:it|test|describe|context)\.skip|x(?:it|describe|test))\s*\(")
SKIP_ANNOT = re.compile(r"^\s*@(?:pytest\.mark\.skip|Disabled|Ignore)\b(?!If|_if)(?:\s*\(\s*\))?(?!\s*\()")
GENERATED = re.compile(r"DO NOT EDIT|@generated|\bcode generated\b|\bauto-?generated\b|this file (is|was) generated|"
                       r"generated by\b", re.I)


def comment_part(line: str, ext: str) -> str:
    """The content of the comment on the line (after removing strings), or an empty string."""
    code = STRING.sub('""', line)
    if ext in HASH_COMMENT:
        i = code.find("#")
        return code[i:] if i >= 0 else ""
    s = code.lstrip()
    if s.startswith(("*", "/*", "<!--")):
        return s
    for tok in ("//", "/*"):
        i = code.find(tok)
        if i >= 0:
            return code[i:]
    return ""


def emit(rule: str, rel: str, line: int, snippet: str, title: str, severity: str, evidence: str,
         suggestion: str, confidence: float = 0.8) -> None:
    print(json.dumps({"rule": rule, "title": title, "file": rel, "line": line, "snippet": snippet.strip()[:160],
                      "severity": severity, "confidence": confidence, "evidence": evidence,
                      "basis": "eng-tech-debt-audit (visible and hidden debt), qa-regression (skipped tests)",
                      "suggestion": suggestion}, ensure_ascii=False))


def blame_ages(root: Path, rel: str) -> dict[int, int]:
    """The line's age in days from `git blame` (an empty dict outside a git repository)."""
    r = subprocess.run(["git", "blame", "--line-porcelain", "--", rel], cwd=root, capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    if r.returncode != 0:
        return {}
    ages, now, line_no = {}, time.time(), 0
    for row in r.stdout.splitlines():
        m = re.match(r"^[0-9a-f]{40} \d+ (\d+)", row)
        if m:
            line_no = int(m.group(1))
        elif row.startswith("committer-time "):
            ages[line_no] = int((now - int(row.split()[1])) // 86400)
    return ages


def in_multiline_string(lines: list[str], ext: str) -> set[int]:
    """Indexes of lines inside multi-line strings (Python `\"\"\"`/`'''`, JS template literals in backticks)."""
    inside, out, delim = False, set(), None
    for i, line in enumerate(lines):
        if inside:
            out.add(i)
        for tok in re.findall(r'\"\"\"|\'\'\'' if ext == ".py" else r"`", line):
            if not inside:
                inside, delim = True, tok
            elif tok == delim:
                inside = False
    return out


def scan_file(root: Path, rel: str, text: str, git: bool) -> None:
    ext = Path(rel).suffix.lower()
    lines = text.splitlines()
    strings = in_multiline_string(lines, ext) if ext in (".py", ".js", ".ts", ".jsx", ".tsx", ".mjs") else set()
    ages: dict[int, int] | None = None
    for i, line in enumerate(lines):
        com = "" if i in strings else comment_part(line, ext)
        if com:
            m = MARKER.search(com)
            if m and not TICKET.search(com):
                if ages is None:
                    ages = blame_ages(root, rel) if git else {}
                age = ages.get(i + 1)
                sev = "medium" if age is not None and age > OLD_DAYS else "low"
                emit("marker-without-ticket", rel, i + 1, line, f"{m.group(1)} without a ticket", sev,
                     f"comment marker with no ticket reference"
                     + (f"; line age {age} days (git blame)" if age is not None else ""),
                     "open a ticket and add its number (e.g. `TODO(#123)`), or fix it and remove the marker")
            sup = None
            if "@ts-ignore" in com:
                sup = "@ts-ignore"
            elif "eslint-disable" in com and "--" not in com.split("eslint-disable", 1)[1]:
                sup = "eslint-disable without a reason"
            elif ext == ".py" and re.search(r"#\s*type:\s*ignore(?!\[)", com):
                sup = "type: ignore without a code"
            elif ext == ".py" and re.search(r"#\s*noqa(?!\s*:)", com, re.I):
                sup = "noqa without a code"
            if sup:
                emit("suppressed-check", rel, i + 1, line, f"suppressed check: {sup}", "low",
                     "a suppression that is not narrowed or has no reason also hides future errors",
                     "narrow the suppression (`@ts-expect-error`, a rule code in `noqa:`/`type: ignore[…]`, a rule in "
                     "`eslint-disable`) and add a reason after ` -- `")
        if SKIP_JS.match(line) or SKIP_ANNOT.match(line):
            prev = lines[i - 1].strip() if i else ""
            has_reason = TICKET.search(line) or prev.startswith(("//", "#", "/*", "*"))
            if not has_reason:
                emit("skipped-test", rel, i + 1, line, "skipped test without a reason", "medium",
                     "test disabled with no reason and no ticket: a regression here will go unnoticed",
                     "fix the test or leave a reason with a ticket (`reason=…`, `@Disabled(\"#123 …\")`, a comment)")
    if ext in CODE_EXT and len(lines) > LARGE and not GENERATED.search("\n".join(lines[:5])):
        emit("large-file", rel, 1, lines[0] if lines else "", f"file has {len(lines)} lines", "low",
             f"{len(lines)} lines (threshold {LARGE})", "split it by responsibility (eng-module-depth, "
             "eng-refactor-planning); write characterization tests first", confidence=0.6)


def list_files(root: Path) -> tuple[list[str], bool]:
    top = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=root, capture_output=True, text=True,
                         encoding="utf-8", errors="replace")
    if top.returncode == 0 and Path(top.stdout.strip()).resolve() == root.resolve():
        r = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, encoding="utf-8",
                           errors="replace")
        return [f for f in r.stdout.splitlines() if f and not set(Path(f).parts) & SKIP_DIRS
                and not f.startswith(FACTORY_OWNED)], True
    out = []
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in SKIP_DIRS]
        out += [str((Path(dp) / f).relative_to(root)) for f in fns]
    return sorted(out), False


def scan(root: Path, files: list[str], git: bool) -> None:
    for rel in files:
        rel = rel.replace(os.sep, "/")
        p = root / rel
        if DOC_OR_FIXTURE.search(rel) or p.suffix.lower() not in CODE_EXT or not p.is_file() \
                or p.stat().st_size > 2_000_000 or ".min." in p.name:
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        scan_file(root, rel, text, git)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--files", default="")
    a = ap.parse_args()
    root = Path(a.root)
    listed, git = list_files(root)
    files = [f for f in a.files.split(",") if f] or listed
    scan(root, files, git)
    return 0


if __name__ == "__main__":
    sys.exit(main())
